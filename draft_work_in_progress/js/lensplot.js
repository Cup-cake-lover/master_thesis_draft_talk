let chart = null;

function initChart() {

    const canvas = document.getElementById("lens-chart");

    if (!canvas) return;

    chart = new Chart(canvas, {

        type: "scatter",

        data: {
            datasets: [
                {
                    label: "Measurements",
                    data: [],
                    pointRadius: 10,
                    pointStyle: 'circle',
                    backgroundColor: "#ff4646",
                    borderColor: "black",
                    borderWidth: 1
                },
                {
                    type: "line",
                    label: "Fit",
                    data: [],
                    pointRadius: 0,
                    borderColor: "red",
                    borderDash: [6, 4],
                    borderWidth: 2
                }
            ]
        },

        options: {
            responsive: true,
            animation: {
                duration: 800
            },
            scales: {
                x: {
                    type: "linear",
                    title: {
                        display: true,
                        text: "f #"
                    }
                },
                y: {
                    title: {
                        display: true,
                        text: "E"
                    }
                }
            }
        }
    });

    setupRevealControls();
}

// ---------------------------
// Reveal.js control logic
// ---------------------------

function setupRevealControls() {

    if (typeof Reveal === "undefined") {
        console.warn("Reveal.js not found");
        return;
    }

    Reveal.on("fragmentshown", (event) => {

        if (!chart) return;

        const id = event.fragment.id;

        if (id === "show-points") {

            chart.data.datasets[0].data = points;
            chart.update();

        }

        if (id === "show-fit") {

            chart.data.datasets[1].data = fit;
            chart.update();

        }
    });

    Reveal.on("fragmenthidden", (event) => {

        if (!chart) return;

        const id = event.fragment.id;

        if (id === "show-points") {
            chart.data.datasets[0].data = [];
            chart.update();
        }

        if (id === "show-fit") {
            chart.data.datasets[1].data = [];
            chart.update();
        }
    });
}

// ---------------------------
// Init after DOM ready
// ---------------------------

window.addEventListener("load", initChart);